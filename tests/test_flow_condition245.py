"""Real conditional operands keep the original value channel and tail position."""
import copy
import unittest
from unittest.mock import patch

from chaos.execution_frames import EvaluationBoundaryFrame
from chaos.language import Evaluator, Native, LanguageError, serializable
from _effect_schedule158 import effect_schedule
import _generator_flow208 as streams
from test_native_jit import NATIVE


FLAVORS = ('fn', 'async fn', 'fn*', 'async fn*')
CONDITIONS = ('predicate()', 'do{predicate()}', 'predicate() && true')


class FlowCondition245(unittest.TestCase):
    def run_case(self, flavor, condition, target, *, flags=None,
                 predicate_value='true', boolean_context=False):
        effects=[];functions=[];boundaries=[];base=[None];focus=[None]
        e=Evaluator(timeout=20,step_limit=30000,
            tool_handler=lambda name,value:effects.append((name,copy.deepcopy(value))) or value)
        def choose(function):
            # The exact source node is shared by original and compiled bodies.
            candidates=[]
            def visit(value):
                if isinstance(value,tuple):
                    if value and value[0]=='if':candidates.append(value)
                    for child in value:visit(child)
                elif type(value) is list:
                    for child in value:visit(child)
            visit(function.body);self.assertEqual(len(candidates),1)
            focus[0]=candidates[0]
            result=streams.compile_choice(e,function,target);functions.append(result);return result
        def mark():base[0]=e.steps
        for name,callback in [('choose',choose),('mark',mark),('effect_count',lambda:len(effects))]:
            e.env.bind(name,Native(name,callback,e,captures=()))
        original=EvaluationBoundaryFrame.step
        def observed(boundary,cursor,value,error):
            node=focus[0]
            if node is not None and boundary.phase=='enter':
                if boundary.node is node and flags is not None:
                    # Authoritative existing activation, no replacement frame.
                    # All four independent combinations must retain their old
                    # meaning, even when not generated by a common source site.
                    boundary.tail,boundary.options['all_results']=flags
                role='condition' if boundary.node is node[1] else 'selected' if boundary.node is node[2] else 'alternate' if boundary.node is node[3] else None
                if role is not None:
                    boundaries.append((role,boundary.tail,boundary.options.get('all_results',False)))
            return original(boundary,cursor,value,error)
        prefix='await sleep(0);' if flavor=='async fn' else 'yield 7;' if flavor=='fn*' else 'await sleep(0);yield 7;' if flavor=='async fn*' else ''
        positive='return_values(true,99)' if boolean_context else 'return_values(42,43)'
        negative='return_values(false,98)' if boolean_context else 'return_values(0,1)'
        expression='if '+condition+'{tool("selected",42);'+positive+'}else{tool("alternate",0);'+negative+'}'
        if boolean_context:expression='[true && ('+expression+')]'
        source='fn predicate(){tool("predicate",'+predicate_value+');return_values('+predicate_value+',99)};let work=choose('+flavor+'(){'+prefix+expression+'});mark();'
        if flavor=='fn':source+='[multiple_value_list(fn(){work()}),effect_count()]'
        elif flavor=='async fn':source+='let task=work();let before=effect_count();await task;[before,multiple_value_list(task),effect_count()]'
        else:
            consume='await acollect(stream)' if flavor=='async fn*' else 'collect(stream)'
            source+='let stream=work();let before=effect_count();let yielded='+consume+';[before,yielded,multiple_value_list(stream),effect_count()]'
        failure=None
        with streams.observe_states() as states,effect_schedule('already_done'),patch.object(EvaluationBoundaryFrame,'step',observed):
            try:result=('value',serializable(e.run(source)))
            except LanguageError as error:failure=error;result=('error',error.record())
            finally:e.suspension.finish(failure)
        self.assertIsNotNone(base[0]);self.assertEqual(e.frames,[]);self.assertEqual(e.depth,0)
        self.assertFalse(e.suspension.active);self.assertIsNone(e.suspension.pool)
        self.assertEqual([row for row in boundaries if row[0]=='condition'],[('condition',False,False)])
        if target in ('raw','interpreter'):self.assertEqual(states,[])
        else:
            self.assertTrue(states,'must execute the actual compiled body')
            for state in states:
                self.assertTrue(state.closed);self.assertEqual(state.frames,[])
                self.assertIsNone(state.pending_cursor);self.assertIsNone(state.pending_request)
                self.assertTrue(state.domain.closed);self.assertEqual(state.domain.live_count,0)
                self.assertTrue(any(row[0]=='operand' for row in state.program.instructions))
                self.assertTrue(any(row[0]=='condition' for row in state.program.instructions))
                self.assertGreater(state.program.native_resumes if target=='native' else state.program.portable_resumes,0)
                if target=='native':self.assertEqual(state.program.portable_resumes,0)
        return (result,e.steps-base[0],effects,boundaries),states

    def assert_value(self,flavor,row,parts=(42,43)):
        terminal=list(parts)
        expected=[terminal,2] if flavor=='fn' else [0,terminal,2] if flavor=='async fn' else [0,[7],terminal,2]
        self.assertEqual(row[0],('value',expected))
        self.assertEqual(row[2],[('predicate',True),('selected',42)])

    def matrix(self,targets):
        for flavor in FLAVORS:
            for condition in CONDITIONS:
                with self.subTest(flavor=flavor,condition=condition):
                    raw,_=self.run_case(flavor,condition,'raw');self.assert_value(flavor,raw)
                    self.assertEqual([r for r in raw[3] if r[0]=='selected'],[('selected',True,True)])
                    for target in targets:
                        actual,_=self.run_case(flavor,condition,target)
                        self.assertEqual(actual,raw,(flavor,condition,target))

    def test_portable_condition_calls_do_and_binary_preserve_four_flavors_and_MV(self):
        self.matrix(('interpreter','portable'))

    @unittest.skipUnless(NATIVE,'optional LLVM backend unavailable')
    def test_real_native_condition_calls_do_and_binary_preserve_four_flavors_and_MV(self):
        self.matrix(('native',))

    def test_original_selected_branch_flags_remain_independent_on_real_activations(self):
        targets=('portable',)+(('native',) if NATIVE else ())
        for flavor in FLAVORS:
            for tail in (False,True):
                for all_results in (False,True):
                    with self.subTest(flavor=flavor,tail=tail,all_results=all_results):
                        raw,_=self.run_case(flavor,'predicate()','raw',flags=(tail,all_results))
                        self.assert_value(flavor,raw,(42,43) if all_results else (42,))
                        self.assertEqual([r for r in raw[3] if r[0]=='selected'],[('selected',tail,all_results)])
                        for target in targets:
                            actual,_=self.run_case(flavor,'predicate()',target,flags=(tail,all_results))
                            self.assertEqual(actual,raw)

    def test_non_tail_boolean_receiver_preserves_full_if_branch_channel(self):
        targets=('interpreter','portable')+(('native',) if NATIVE else ())
        for flavor in FLAVORS:
            with self.subTest(flavor=flavor):
                raw,_=self.run_case(flavor,'predicate()','raw',boolean_context=True)
                expected=[[[True]],2] if flavor=='fn' else [0,[[True]],2] if flavor=='async fn' else [0,[7],[[True]],2]
                self.assertEqual(raw[0],('value',expected));self.assertEqual(raw[2],[('predicate',True),('selected',42)])
                self.assertEqual([r for r in raw[3] if r[0]=='selected'],[('selected',False,True)])
                for target in targets:
                    actual,_=self.run_case(flavor,'predicate()',target,boolean_context=True)
                    self.assertEqual(actual,raw)

    def test_false_condition_commits_only_original_alternate_branch(self):
        for flavor in FLAVORS:
            with self.subTest(flavor=flavor):
                raw,_=self.run_case(flavor,'predicate()','raw',predicate_value='false')
                expected=[[0,1],2] if flavor=='fn' else [0,[0,1],2] if flavor=='async fn' else [0,[7],[0,1],2]
                self.assertEqual(raw[0],('value',expected))
                self.assertEqual(raw[2],[('predicate',False),('alternate',0)])
                self.assertEqual([r for r in raw[3] if r[0]=='alternate'],[('alternate',True,True)])
                for target in ('portable',)+(('native',) if NATIVE else ()):
                    actual,_=self.run_case(flavor,'predicate()',target,predicate_value='false')
                    self.assertEqual(actual,raw)

    def test_non_bool_primary_is_rejected_before_either_branch(self):
        for flavor in FLAVORS:
            with self.subTest(flavor=flavor):
                raw,_=self.run_case(flavor,'predicate()','raw',predicate_value='42')
                self.assertEqual(raw[0][0],'error');self.assertIn('Bool',raw[0][1]['message'])
                self.assertNotIn('TailCall',raw[0][1]['message']);self.assertEqual(raw[2],[('predicate',42)])
                self.assertEqual([r for r in raw[3] if r[0]!='condition'],[])
                for target in ('portable',)+(('native',) if NATIVE else ()):
                    actual,_=self.run_case(flavor,'predicate()',target,predicate_value='42')
                    self.assertEqual(actual,raw)
